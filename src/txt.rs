bitflags! {
    #[derive(Copy, Clone, Debug, PartialEq)]
    pub struct FontStyle: u8 {
        const NORMAL = 0b00000001;
        const BOLD   = 0b00000010;
        const SHADOW = 0b00000100;
    }
}

#[derive(Clone, Copy, Debug)]
pub enum FontType {
    Font8x8,
    SwissFont,
}

/// 字形结构，使用静态引用避免堆分配
#[derive(Debug, Clone, Copy)]
pub struct Glyph {
    pub data: &'static [u8],
}

impl Glyph {
    /// 从静态字节数组创建字形
    pub const fn new(data: &'static [u8]) -> Self {
        Self { data }
    }

    pub fn width(&self) -> u8 {
        if self.data.is_empty() { 0 } else { self.data[0] }
    }

    pub fn height(&self) -> u8 {
        if self.data.len() < 2 { 0 } else { self.data[1] }
    }

    pub fn bitmap(&self) -> &[u8] {
        if self.data.len() < 2 { &[] } else { &self.data[2..] }
    }

    /// 将字体字节数据转换为像素数组
    /// 使用LSB优先的位顺序：bit0(最低位)对应最左边的像素
    pub fn create_image(&self, color: u8) -> (i32, i32, Vec<u8>) {
        let width = self.width() as i32;
        let height = self.height() as i32;
        let bitmap_data = self.bitmap();

        let mut pixels = vec![0u8; (width * height) as usize];

        for row in 0..height {
            for col in 0..width {
                let bit_index = (row * width + col) as usize;
                let byte_index = bit_index / 8;
                let bit_offset = bit_index % 8;

                if byte_index < bitmap_data.len() {
                    let byte = bitmap_data[byte_index];
                    let bit = (byte >> bit_offset) & 1;
                    let pixel_index = (row * width + col) as usize;
                    if bit == 1 {
                        pixels[pixel_index] = color;
                    }
                }
            }
        }

        (width, height, pixels)
    }
}

