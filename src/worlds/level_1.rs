/// 关卡 1A 特性统计
pub struct Level1AStats {
    /// 总列数 (地图宽度)
    pub total_columns: usize,
    /// 总行数 (地图高度)
    pub total_rows: usize,
    /// 砖块数量
    pub brick_count: usize,
    /// 问号方块数量
    pub question_block_count: usize,
    /// 敌人数量
    pub enemy_count: usize,
    /// 金币数量
    pub coin_count: usize,
    /// 可收集物品数量
    pub collectible_count: usize,
    /// 水管入口数量
    pub pipe_entrance_count: usize,
}

impl Level1AStats {
    /// 分析地图数据，生成关卡统计信息
    pub fn analyze() -> Self {
        let total_rows = LEVEL_1A_MAP.len();
        let total_columns = if total_rows > 0 {
            LEVEL_1A_MAP[0].len()
        } else {
            0
        };

        let mut brick_count = 0;
        let mut question_block_count = 0;
        let mut enemy_count = 0;
        let mut coin_count = 0;
        let mut collectible_count = 0;
        let mut pipe_entrance_count = 0;

        for row in LEVEL_1A_MAP.iter() {
            for &ch in row.iter() {
                match ch {
                    // 砖块范围: 0xF4-0xFA, 0xF6, 0xF7, 0xF8, 0xF9, 0xFE
                    0xF4 | 0xF5 | 0xF6 | 0xF7 | 0xF8 | 0xF9 | 0xFA | 0xFE => brick_count += 1,
                    0x3F => question_block_count += 1, // '?'
                    0x4A | 0x4B => enemy_count += 1,   // 'J', 'K'
                    0x24 => coin_count += 1,           // '$'
                    0x2A => collectible_count += 1,    // '*'
                    0x49 => pipe_entrance_count += 1,  // 'I'
                    _ => {}
                }
            }
        }

        Self {
            total_columns,
            total_rows,
            brick_count,
            question_block_count,
            enemy_count,
            coin_count,
            collectible_count,
            pipe_entrance_count,
        }
    }

    /// 打印关卡统计信息（调试用，已禁用）
    #[allow(dead_code)]
    pub fn print_stats(&self) {
        // 调试输出已禁用
        let _ = (self.total_columns, self.total_rows, self.brick_count,
                 self.question_block_count, self.enemy_count, self.coin_count,
                 self.collectible_count, self.pipe_entrance_count);
    }
}

/// 验证地图数据的完整性
pub fn validate_map_data() -> Result<(), String> {
    if LEVEL_1A_MAP.is_empty() {
        return Err("地图数据为空".to_string());
    }

    let expected_width = LEVEL_1A_MAP[0].len();
    for (i, row) in LEVEL_1A_MAP.iter().enumerate() {
        if row.len() != expected_width {
            return Err(format!(
                "第 {} 行长度不一致: 期望 {}, 实际 {}",
                i + 1,
                expected_width,
                row.len()
            ));
        }
    }

    Ok(())
}

/// 获取指定位置的地图块类型
pub fn get_tile_at(x: usize, y: usize) -> Option<u8> {
    if y < LEVEL_1A_MAP.len() {
        if x < LEVEL_1A_MAP[y].len() {
            return Some(LEVEL_1A_MAP[y][x]);
        }
    }
    None
}

/// 检查指定位置是否为固体方块（可碰撞）
pub fn is_solid_tile(x: usize, y: usize) -> bool {
    match get_tile_at(x, y) {
        // 砖块: 0xF4-0xFA, 墙体: 0x57 ('W'), 地面: 0x23/0x25 ('#%'), 装饰: 0x30-0x33 ('0'-'3')
        Some(ch) => matches!(
            ch,
            0xF4 | 0xF5
                | 0xF6
                | 0xF7
                | 0xF8
                | 0xF9
                | 0xFA
                | 0xFE
                | 0x57
                | 0x23
                | 0x25
                | 0x30
                | 0x31
                | 0x32
                | 0x33
        ),
        None => false,
    }
}

/// 检查指定位置是否为可破坏方块
pub fn is_breakable_tile(x: usize, y: usize) -> bool {
    match get_tile_at(x, y) {
        // 砖块范围
        Some(ch) => matches!(ch, 0xF4 | 0xF5 | 0xF6 | 0xF7 | 0xF8 | 0xF9 | 0xFA | 0xFE),
        _ => false,
    }
}

/// 检查指定位置是否为问号方块
pub fn is_question_block(x: usize, y: usize) -> bool {
    match get_tile_at(x, y) {
        Some(0x3F) => true, // '?'
        _ => false,
    }
}

