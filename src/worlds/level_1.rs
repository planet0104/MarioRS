//! 关卡 1A 数据与逻辑
//!
//! 本模块包含关卡 1A 的完整实现，包括：
//! - 地图数据 (Level_1a) - 180行 × 13列字节数组
//! - 配置选项 (OPTIONS_1A, OPT_1A)  
//! - 关卡特定的游戏逻辑与辅助函数
//! - Level1A 封装类，提供 run() 方法运行关卡
