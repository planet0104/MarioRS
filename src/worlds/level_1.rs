//!
//! ## 地图字节编码说明
//!
//! 地图数据从 Pascal 的 ISO-8859-1 编码精确转换而来，每个字节代表一个游戏元素：
//!
//! ### 基础元素
//! - `0x41` ('A') - 天空背景标记
//! - `0x23` ('#') - 地面标记（第一字节）
//! - `0x25` ('%') - 地面标记（第二字节）
//! - `0x20` (' ') - 空白/空气
//!
//! ### 砖块与平台（可破坏/交互）
//! - `0xF4` - 砖块类型 1
//! - `0xF5` - 砖块类型 2  
//! - `0xF6` - 砖块类型 3
//! - `0xF7` - 特殊砖块
//! - `0xF8` - 砖块类型 5
//! - `0xF9` - 砖块类型 6
//! - `0xFA` - 砖块类型 7
//! - `0xFE` - 特殊砖块 2
//!
//! ### 墙体与障碍（不可破坏）
//! - `0x57` ('W') - 木质墙体方块（WOOD.000.png，颜色由 WoodColor 配置决定）
//!
//! ### 交互物品
//! - `0x3F` ('?') - 问号方块（含道具/金币）
//! - `0x24` ('$') - 金币
//! - `0x2A` ('*') - 可收集物品/蘑菇/火焰花
//!
//! ### 敌人
//! - `0x4A` ('J') - 跳跃敌人 (Jump enemy / 板栗仔)
//! - `0x4B` ('K') - 飞行敌人 (Koopa / 乌龟)
//!
//! ### 地形装饰
//! - `0x30` ('0') - 地形装饰 1
//! - `0x31` ('1') - 地形装饰 2
//! - `0x32` ('2') - 地形装饰 3
//! - `0x33` ('3') - 地形装饰 4
//!
//! ### 特殊标记
//! - `0x49` ('I') - 水管入口
//! - `0x80` - 特殊标记 1
//! - `0x88` - 特殊标记 2
//! - `0xE0` - 地形特效 1
//! - `0xE2` - 地形特效 2
//! - `0xE7` - 地形特效 3
